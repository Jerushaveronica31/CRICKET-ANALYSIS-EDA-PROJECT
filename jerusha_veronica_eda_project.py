# Outlier Treatment using IQR Capping (Winsorization) on the batting dataset
df_original = df_clean.copy()

# Numeric columns in our dataset where we want to cap extreme values
outlier_columns = ["runs", "average", "strike_rate", "balls_faced", "fours", "sixes"]

df_treated = df_original.copy()

for col in outlier_columns:
    if col in df_treated.columns:
        q1 = df_treated[col].quantile(0.25)
        q3 = df_treated[col].quantile(0.75)
        iqr = q3 - q1
        lower_bound = q1 - 1.5 * iqr
        upper_bound = q3 + 1.5 * iqr

        # Cap values outside the 1.5 * IQR limits
        df_treated[col] = df_treated[col].clip(lower=lower_bound, upper=upper_bound)

print("Outlier capping completed successfully on columns:", outlier_columns)
display(df_treated.head())

